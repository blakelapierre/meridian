test("a floor holds a post and a salvaged sentence falls as a slip", () => {
  const yard = createYard({ x: 0, y: 0 });
  const cell = [8, 8];
  assert.equal(tryPlaceFloor(yard, cell).ok, true);
  assert.equal(tryPlacePost(yard, cell).ok, true);
  const wall = yard.pieces.find((piece) => piece.id === "footing");
  const beside = [wall.at[0] + 1, wall.at[1]];
  yard.pieces.push({ id: "wall", at: beside, anchors: false, line: "the well is north", by: "ada" });
  assert.equal(trySalvage(yard, beside).ok, true);
  const slip = yard.pieces.find((piece) => piece.id === "slip");
  assert.equal(slip.text, "the well is north");
});

