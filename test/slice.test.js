test("the next slice pays a defuse, spans a beam, and reads the landing counter", () => {
  assert.equal(seaGain("noon"), 0.5);
  assert.equal(seaGain("night"), 0.3);
  assert.equal(seaGain("dawn"), 1);
  const skills = createSkills();
  skills.jump.value = 30;
  assert.equal(seedLanding(skills), 3);
  assert.equal(fallFromCount(100, -12, 3), 95);
  assert.equal(countLanding(skills), 4);
  const armed = afterShot();
  assert.equal(armed.lock, 12);
  assert.equal(stepShotWait(0, armed.reload).reload, 7);
  assert.equal(defusePay({ defused: true }), 8);
  assert.equal(defusePay({ defused: false }), 0);
  const yard = createYard({ x: 0, y: 0 });
  const at = yard.pieces[0].at;
  yard.pieces.push({ id: "post", at: [at[0], at[1] + 3], anchors: false });
  yard.pieces.push({ id: "post", at: [at[0] + 2, at[1] + 3], anchors: false });
  assert.equal(tryPlaceBeam(yard, [at[0] + 1, at[1] + 3]).ok, true);
  yard.pieces.push({ id: "wall", at: [at[0] + 4, at[1]], anchors: false, line: "north", by: "ada", sig: 9 });
  trySalvage(yard, [at[0] + 4, at[1]]);
  assert.equal(yard.pieces.find((piece) => piece.id === "slip").sig, 9);
  assert.equal(firePull(["ada"]), 0.04);
  assert.equal(firePull(["ada", "bea"]), 0.07);
  assert.equal(firePull(["ada", "bea", "cy"]), 0.07);
  assert.equal(fluxMetal(DAY_NOON, 0, false) > fluxMetal(DAY_NOON, 1, false), true);
});

const DAY_NOON = 72 * 60 * 30 / 4;

test("a stored no changes quorum, a purse spends, and a slump is written", () => {
  assert.equal(tally(1, 0).pass, true);
  assert.equal(tally(1, 1).pass, false);
  const purse = { ada: 2 };
  assert.equal(spendPurse(purse, "ada", 1), true);
  assert.equal(purse.ada, 1);
  const skills = createSkills();
  skills.appraisal.value = 8;
  assert.equal(teachMore(skills), "appraisal");
  assert.equal(skills.appraisal.value, 12);
  const pools = [];
  const pool = notePool(pools, { x: 1, y: 1, floor: -0.3 });
  const lowered = lowerPool(pools, true);
  const spilled = spillPool(lowered);
  assert.equal(spilled.y, pool.y + 0.5);
  const yard = createYard({ x: 0, y: 0 });
  const cartAt = yard.pieces[0].at.slice();
  yard.pieces.push({ id: "cart", at: cartAt, anchors: false, load: 2, wait: 2 });
  yard.pieces.push({ id: "road", at: [cartAt[0] + 1, cartAt[1]], anchors: true });
  assert.equal(rollCart(yard), true);
  assert.equal(yard.pieces.find((piece) => piece.id === "cart").at[0], cartAt[0] + 1);
  assert.equal(graceMark({ cell: [0, 0] }, true).grace, true);
  const phrase = recoveryPhrase({ pubkey: Uint8Array.from([1, 2, 3, 4, 5, 6]) });
  assert.equal(phrase.split(" ").length, 6);
  const spore = raiseSpore(true, [0, 1, 1]);
  assert.equal(spore.spore, true);
  const table = {};
  writeVoucher(table, "self");
  assert.equal(readVoucher(table), "self");
  const feet = stepDrag([0, 0, 0], dragAsk(true), 0, 1);
  assert.notEqual(feet[1], 0);
  const push = windPush([1, 0, 0]);
  assert.ok(push[0] > 0);
  assert.equal(bitMode(true, "smooth"), "smooth");
  assert.equal(bitMode(false, "smooth"), "slump");
  const crust = new Crust();
  crust.write(0, 0, 0, 1000);
  crust.write(0, 1, 0, 0);
  assert.equal(applySlump(crust, [12, 12, 12]), 875);
  const identity = createIdentity();
  const heard = acceptLore(encodeLore(identity, { nonce: 1, notes: ["a wall fell"], harm: 1 }));
  assert.equal(heard.harm, 1);
  assert.ok(heard.sig > 0);
});

test("the slice that followed a scale run: soak, a stored yes, a lean, and a phrase in a book", () => {
  assert.match(landingNote({ landing: { falls: 3 } }), /land 3 soak 3/);
  assert.match(landingNote({ landing: { falls: 9 } }), /soak 6/);
  const stored = new Map([["atoll-1", true], ["elsewhere", false]]);
  const vote = tallyStored(1, stored);
  assert.equal(vote.yes, 1);
  assert.equal(vote.present, 2);
  assert.equal(vote.pass, false);
  assert.equal(overheadCamera(false, 1, 2), null);
  const pose = overheadCamera(true, 1, 2);
  assert.equal(pose.camera, "overhead");
  assert.equal(pose.height, 18);
  assert.notEqual(payPurse("defuse").purse, payPurse("round").purse);
  assert.equal(payPurse("defuse").metal, 8);
  assert.equal(payPurse("round").metal, 8);
  assert.ok(missDir([0, 1, 0], 0.04)[0] > 0);
  assert.equal(missDir([0, 1, 0], 0)[0], 0);
  assert.equal(spendMagazine(6, { lock: 0, reload: 8 }), 5);
  assert.equal(spendMagazine(6, { lock: 2, reload: 8 }), 6);
  const orders = new Map();
  giveOrder(orders, "ada", "hold");
  assert.equal(orders.get("ada"), "hold");
  const table = { voucher: "self" };
  clearVoucher(table, true);
  assert.equal(table.voucher, "");
  const skills = createSkills();
  skills.appraisal.value = 40;
  assert.equal(teachAtCap(skills.appraisal), true);
  assert.equal(teachMore(skills), null);
  const deed = peerDeed({ cell: [1, 2], holder: "ada", radius: 6 }, true);
  assert.equal(deed.grace, true);
  assert.equal(deed.holder, "ada");
  const purse = { ada: 3 };
  assert.equal(buyFromPurse(purse, "ada", "wall"), false);
  assert.equal(purse.ada, 3);
  assert.deepEqual(readDragMessage(dragMessage("ada")), { id: "ada", walk: true });
  const filled = fillCell({ x: 1, y: 1, floor: -0.5, key: "1,1" });
  assert.equal(filled.filled, filled.y);
  assert.ok(filled.y > 1);
  assert.deepEqual(spreadSpore({ spore: true }, "atoll-0").cells, ["atoll-0", "atoll-1"]);
  assert.equal(bodyLean([1, 0, 0], false), 0);
  assert.notEqual(bodyLean([1, 0, 0], true), 0);
  assert.equal(certifySlump(true).certified, false);
  const crust = new Crust();
  crust.write(0, 0, 0, 1000);
  crust.write(0, 1, 0, 0);
  assert.equal(acceptCertifiedSlump(crust, [12, 12, 12], certifySlump(true)), null);
  assert.equal(acceptCertifiedSlump(crust, [12, 12, 12], certifySlump(false)), 875);
  const yard = createYard({ x: 0, y: 0 });
  const cartAt = yard.pieces[0].at.slice();
  yard.pieces.push({ id: "cart", at: cartAt.slice(), anchors: false, load: 1, wait: 2 });
  yard.pieces.push({ id: "road", at: [cartAt[0] + 1, cartAt[1]], anchors: true });
  assert.equal(rollCart(yard), true);
  assert.deepEqual(yard.pieces.find((piece) => piece.id === "cart").look, cartAt);
  const cell = [3, 3];
  yard.stone = 4;
  yard.pieces.push({ id: "beam", at: cell.slice(), anchors: false });
  assert.equal(tryPlaceFloor(yard, cell).held, true);
  assert.equal(slipChecks({ id: "slip", sig: 9 }, 9), true);
  assert.equal(slipChecks({ id: "slip", sig: 9 }, 4), false);
  const who = createIdentity();
  const book = {};
  rememberKey(book, who);
  const phrase = recoveryPhrase(who);
  const back = restoreKey(unpackBook(packBook(book)), phrase);
  assert.deepEqual([...back.pubkey], [...who.pubkey]);
  assert.equal(restoreKey({}, phrase), null);
  assert.equal(grazeAnimal(graze({ stock: 1 })).kind, "graze");
  assert.deepEqual(finCredit(2), { credit: "fin", metal: 2 });
  assert.equal(finCredit(0), null);
});
